/* =====================================================================
   ШАБЛОН ДИСЦИПЛИНЫ. Скопируйте файл, переименуйте в <id>.js, замените
   содержимое и впишите id в data/manifest.js.
   Демо можно удалить: файл demo.js + слово "demo" в manifest.js.

   [НЕ УДАЛЯТЬ] обёртку `(window.QUIZ_DATA = window.QUIZ_DATA || []).push({...})`:
   по ней js/store.js находит дисциплину. Она не зависит от порядка
   подключения скриптов.

   Формат вопроса:
     { question: "Текст",
       answers: [ { text: "Вариант", correct: true }, { text: "Вариант", correct: false } ],
       explanation: "Пояснение (необязательно)" }
   • правильных ответов может быть несколько → вопрос с множественным выбором;
   • минимум 2 варианта и 1 правильный; число вариантов — любое (в старой версии
     везде было 5 или 4, теперь не обязательно);
   • в тексте можно писать < > & — всё показывается как обычный текст;
   • ЗАПЯТЫЕ: после каждого вопроса и варианта, кроме последнего. Одна
     пропущенная запятая делает недоступной ТОЛЬКО эту дисциплину
     (остальные продолжат работать). Комментарии допустимы: // и блочные.
   ===================================================================== */
(window.QUIZ_DATA = window.QUIZ_DATA || []).push({
  id: "demo",                       // = имя файла, латиница/цифры/-/_
  title: "Демо-дисциплина",         // что видит пользователь
  description: "Пример формата. Удалите, когда добавите свои.",
  questions: [
    {
      question: "Столица Казахстана?",
      answers: [
        { text: "Астана", correct: true },
        { text: "Алматы", correct: false },
        { text: "Шымкент", correct: false }
      ],
      explanation: "Пояснение показывается после ответа."
    },
    {
      question: "Выберите все простые числа",
      answers: [
        { text: "2", correct: true },
        { text: "3", correct: true },
        { text: "4", correct: false },
        { text: "6", correct: false }
      ]
    },
    {
      question: "Сколько вариантов ответа может быть у вопроса?",
      answers: [
        { text: "Любое число, от 2", correct: true },
        { text: "Строго 5", correct: false }
      ]
    }
  ]
});
